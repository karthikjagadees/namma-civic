"""Pure scoring and decision logic for likely duplicate civic reports."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
import math
import re
import unicodedata
from typing import Mapping, Optional, Sequence

from app.deduplication.images import phash_similarity
from app.deduplication.text import character_ngram_similarity, token_jaccard_similarity


class MatchDecision(str, Enum):
    """Next action returned by the duplicate resolver."""

    auto_link = "auto_link"
    officer_review = "officer_review"
    new_incident = "new_incident"


@dataclass(frozen=True)
class ReportEvidence:
    """Incoming report evidence, independent of ORM and LangGraph state."""

    report_id: str
    text: str
    category: str
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    location_confidence: Optional[float] = None
    location_accuracy_m: Optional[float] = None
    address: Optional[str] = None
    landmark: Optional[str] = None
    photo_hashes: tuple[str, ...] = ()
    channel: Optional[str] = None
    reported_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


@dataclass(frozen=True)
class CandidateIncident:
    """An incident and bounded report evidence retrieved by the repository."""

    incident_id: str
    title: str
    report_texts: tuple[str, ...]
    category: str
    status: str
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    location_confidence: Optional[float] = None
    location_accuracy_m: Optional[float] = None
    address: Optional[str] = None
    landmark: Optional[str] = None
    photo_hashes: tuple[str, ...] = ()
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    last_reported_at: Optional[datetime] = None


@dataclass(frozen=True)
class CandidateScore:
    """Fused score and individual explainable signals for one candidate."""

    incident_id: str
    fused_score: float
    signals: Mapping[str, Optional[float]]
    distance_m: Optional[float]


@dataclass(frozen=True)
class Thresholds:
    """Decision thresholds generated by the labeled synthetic calibration run."""

    auto_link: float = 0.66
    review: float = 0.58


@dataclass(frozen=True)
class MatchResult:
    """Resolver decision with ranked candidates, recurrence target, and failures."""

    decision: MatchDecision
    incident_id: Optional[str] = None
    recurrence_of_incident_id: Optional[str] = None
    candidate_scores: tuple[CandidateScore, ...] = ()
    reasons: tuple[str, ...] = ()
    failures: tuple[str, ...] = ()

    @property
    def best_score(self) -> Optional[float]:
        """Return the highest candidate score when candidates were available."""
        return self.candidate_scores[0].fused_score if self.candidate_scores else None


SIGNAL_WEIGHTS: Mapping[str, float] = {
    "distance": 0.24,
    "category": 0.16,
    "token_similarity": 0.12,
    "character_ngram_similarity": 0.14,
    "image_phash": 0.18,
    "time": 0.06,
    "address_landmark": 0.10,
}

CATEGORY_RADIUS_M: Mapping[str, float] = {
    "pothole": 100.0,
    "garbage": 60.0,
    "water_leakage": 80.0,
    "street_light": 45.0,
    "drainage": 75.0,
    "traffic_signal": 60.0,
    "encroachment": 80.0,
    "other": 75.0,
}
_COMPATIBLE_CATEGORIES = {
    frozenset(("pothole", "drainage")): 0.25,
    frozenset(("garbage", "encroachment")): 0.20,
}
_ACTIVE_STATUSES = {"open", "in_progress"}
_CANDIDATE_WINDOW_DAYS = 365
_DECISIVE_PHOTO_SIMILARITY = 0.95
_DECISIVE_PHOTO_MAX_DISTANCE_M = 20.0


def _category_similarity(first: str, second: str) -> float:
    """Return exact, cautious related-category, or incompatible-category score."""
    if first == second:
        return 1.0
    return _COMPATIBLE_CATEGORIES.get(frozenset((first, second)), 0.0)


def _distance_signal(report: ReportEvidence, candidate: CandidateIncident) -> tuple[Optional[float], Optional[float]]:
    """Return normalized proximity and exact Haversine distance."""
    if None in (report.latitude, report.longitude, candidate.latitude, candidate.longitude):
        return None, None
    latitude_1 = math.radians(report.latitude)
    latitude_2 = math.radians(candidate.latitude)
    latitude_delta = latitude_2 - latitude_1
    longitude_delta = math.radians(candidate.longitude - report.longitude)
    haversine = (
        math.sin(latitude_delta / 2.0) ** 2
        + math.cos(latitude_1) * math.cos(latitude_2) * math.sin(longitude_delta / 2.0) ** 2
    )
    distance = 6_371_000.0 * 2.0 * math.atan2(math.sqrt(haversine), math.sqrt(1.0 - haversine))
    base_radius = CATEGORY_RADIUS_M.get(report.category, CATEGORY_RADIUS_M["other"])
    uncertainty = min(report.location_accuracy_m or 0.0, base_radius)
    uncertainty += min(candidate.location_accuracy_m or 0.0, base_radius)
    effective_distance = max(0.0, distance - uncertainty)
    distance_score = max(0.0, 1.0 - effective_distance / base_radius)
    certainty = base_radius / (base_radius + uncertainty)
    reported_confidences = [
        value for value in (report.location_confidence, candidate.location_confidence)
        if value is not None
    ]
    confidence_factor = math.prod(reported_confidences) if reported_confidences else 1.0
    return distance_score * certainty * confidence_factor, distance


def _time_signal(report: ReportEvidence, candidate: CandidateIncident) -> float:
    """Return linear recency score over a 180-day comparison window."""
    last_seen = candidate.last_reported_at or candidate.created_at
    report_at = report.reported_at
    if report_at.tzinfo is None:
        report_at = report_at.replace(tzinfo=timezone.utc)
    if last_seen.tzinfo is None:
        last_seen = last_seen.replace(tzinfo=timezone.utc)
    age_days = abs((report_at - last_seen).total_seconds()) / 86400.0
    return max(0.0, 1.0 - age_days / 180.0)


def _candidate_in_time_window(report: ReportEvidence, candidate: CandidateIncident) -> bool:
    """Only compare open or resolved incidents from the prior 365 days."""
    reported_at = report.reported_at
    created_at = candidate.last_reported_at or candidate.created_at
    if reported_at.tzinfo is None:
        reported_at = reported_at.replace(tzinfo=timezone.utc)
    if created_at.tzinfo is None:
        created_at = created_at.replace(tzinfo=timezone.utc)
    return abs((reported_at - created_at).total_seconds()) <= _CANDIDATE_WINDOW_DAYS * 86400


def _normalize_place(value: Optional[str]) -> str:
    """Normalize a place string for explainable exact/overlap comparison."""
    if not value:
        return ""
    return " ".join(re.findall(r"\w+", unicodedata.normalize("NFKC", value).casefold()))


def _place_signal(report: ReportEvidence, candidate: CandidateIncident) -> Optional[float]:
    """Compare address and landmark strings without treating text as location proof alone."""
    report_places = {_normalize_place(report.address), _normalize_place(report.landmark)} - {""}
    candidate_places = {_normalize_place(candidate.address), _normalize_place(candidate.landmark)} - {""}
    if not report_places or not candidate_places:
        return None
    if report_places & candidate_places:
        return 1.0
    report_tokens = set(" ".join(report_places).split())
    candidate_tokens = set(" ".join(candidate_places).split())
    if not report_tokens or not candidate_tokens:
        return 0.0
    return len(report_tokens & candidate_tokens) / len(report_tokens | candidate_tokens)


def _image_signal(report: ReportEvidence, candidate: CandidateIncident) -> Optional[float]:
    """Return best pairwise pHash similarity, or None when no images are available."""
    if not report.photo_hashes or not candidate.photo_hashes:
        return None
    return max(phash_similarity(left, right) for left in report.photo_hashes for right in candidate.photo_hashes)


def score_candidate(report: ReportEvidence, candidate: CandidateIncident) -> CandidateScore:
    """Calculate transparent per-signal evidence and a missing-signal normalized score."""
    distance, distance_m = _distance_signal(report, candidate)
    candidate_text = "\n".join((candidate.title, *candidate.report_texts))
    report_place_text = " ".join(part for part in (report.text, report.address, report.landmark) if part)
    signals: dict[str, Optional[float]] = {
        "distance": distance,
        "category": _category_similarity(report.category, candidate.category),
        "token_similarity": token_jaccard_similarity(report_place_text, candidate_text),
        "character_ngram_similarity": character_ngram_similarity(report_place_text, candidate_text),
        "image_phash": _image_signal(report, candidate),
        "time": _time_signal(report, candidate),
        "address_landmark": _place_signal(report, candidate),
    }
    available = [(SIGNAL_WEIGHTS[name], value) for name, value in signals.items() if value is not None]
    denominator = sum(weight for weight, _ in available)
    fused = sum(weight * float(value) for weight, value in available) / denominator if denominator else 0.0
    return CandidateScore(candidate.incident_id, min(1.0, max(0.0, fused)), signals, distance_m)


def match_report(
    report: ReportEvidence,
    candidates: Sequence[CandidateIncident],
    thresholds: Thresholds = Thresholds(),
) -> MatchResult:
    """Rank candidates and select safe link, review, new incident, or recurrence."""
    try:
        eligible = [
            candidate for candidate in candidates
            if candidate.status in _ACTIVE_STATUSES | {"resolved"}
            and _candidate_in_time_window(report, candidate)
        ]
        scores = [score_candidate(report, candidate) for candidate in eligible]
    except Exception as exc:
        return MatchResult(
            MatchDecision.officer_review,
            reasons=("A duplicate signal could not be computed; officer review is required.",),
            failures=(f"{type(exc).__name__}: signal calculation failed",),
        )
    scores.sort(key=lambda item: (-item.fused_score, item.distance_m if item.distance_m is not None else math.inf, item.incident_id))
    if report.latitude is None or report.longitude is None:
        return MatchResult(
            MatchDecision.officer_review,
            candidate_scores=tuple(scores),
            reasons=("Location evidence is unresolved; text alone cannot auto-link reports.",),
        )

    review_candidates = [item for item in scores if item.fused_score >= thresholds.review]
    candidate_status = {candidate.incident_id: candidate.status for candidate in candidates}
    active_matches = [item for item in review_candidates if candidate_status.get(item.incident_id) in _ACTIVE_STATUSES]
    resolved_matches = [item for item in review_candidates if candidate_status.get(item.incident_id) == "resolved"]

    # A unique near-exact photo match at the same location can distinguish an
    # active incident from nearby same-category cases with merely similar text.
    decisive_photo_matches = [
        item for item in scores
        if item.signals.get("image_phash") is not None
        and item.signals["image_phash"] >= _DECISIVE_PHOTO_SIMILARITY
        and item.signals.get("category") == 1.0
        and item.distance_m is not None
        and item.distance_m <= _DECISIVE_PHOTO_MAX_DISTANCE_M
    ]
    if len(decisive_photo_matches) == 1:
        exact_photo_match = decisive_photo_matches[0]
        matched_status = candidate_status.get(exact_photo_match.incident_id)
        if exact_photo_match.fused_score >= thresholds.auto_link and matched_status in _ACTIVE_STATUSES:
            return MatchResult(
                MatchDecision.auto_link,
                incident_id=exact_photo_match.incident_id,
                candidate_scores=tuple(scores),
                reasons=("A unique near-exact photo and same-category match within 20 m identifies the active incident.",),
            )
        if exact_photo_match.fused_score >= thresholds.auto_link and matched_status == "resolved":
            return MatchResult(
                MatchDecision.new_incident,
                recurrence_of_incident_id=exact_photo_match.incident_id,
                candidate_scores=tuple(scores),
                reasons=("A unique near-exact photo match identifies a resolved incident; create a separate recurrence.",),
            )

    if active_matches and resolved_matches:
        return MatchResult(
            MatchDecision.officer_review,
            candidate_scores=tuple(scores),
            reasons=("The report could connect an active incident and a resolved recurrence candidate.",),
        )
    if len(active_matches) > 1 or len(resolved_matches) > 1:
        return MatchResult(
            MatchDecision.officer_review,
            candidate_scores=tuple(scores),
            reasons=("The report may bridge multiple existing incidents.",),
        )
    if resolved_matches:
        best_resolved = resolved_matches[0]
        if best_resolved.fused_score >= thresholds.auto_link:
            return MatchResult(
                MatchDecision.new_incident,
                recurrence_of_incident_id=best_resolved.incident_id,
                candidate_scores=tuple(scores),
                reasons=("A strong match to a resolved incident is a recurrence reference; create a new incident.",),
            )
        return MatchResult(
            MatchDecision.officer_review,
            candidate_scores=tuple(scores),
            reasons=("Possible recurrence of a resolved incident needs officer review.",),
        )
    if active_matches:
        best = active_matches[0]
        # A strong contradiction between two supplied photos is an important
        # false-merge warning. Keep it reviewable even when text/place match.
        image_score = best.signals.get("image_phash")
        if image_score is not None and image_score < 0.25:
            return MatchResult(
                MatchDecision.officer_review,
                candidate_scores=tuple(scores),
                reasons=("Photo evidence strongly conflicts with the best candidate; officer review is required.",),
            )
        if best.fused_score >= thresholds.auto_link:
            return MatchResult(
                MatchDecision.auto_link,
                incident_id=best.incident_id,
                candidate_scores=tuple(scores),
                reasons=("Best active candidate exceeded the calibrated auto-link threshold.",),
            )
        return MatchResult(
            MatchDecision.officer_review,
            candidate_scores=tuple(scores),
            reasons=("Best active candidate is in the officer-review score band.",),
        )
    return MatchResult(
        MatchDecision.new_incident,
        candidate_scores=tuple(scores),
        reasons=("No eligible incident candidate met the review threshold.",),
    )
